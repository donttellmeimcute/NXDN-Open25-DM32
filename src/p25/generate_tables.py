#!/usr/bin/env python3
"""Generate mathematical Golay syndrome corrections; no upstream table input."""
from itertools import combinations
from pathlib import Path
import sys


def syndrome(pattern):
    for bit in range(22, 10, -1):
        if pattern & (1 << bit):
            pattern ^= 0xc75 << (bit - 11)
    return pattern


table = [None] * 2048
for weight in range(4):
    for bits in combinations(range(23), weight):
        mask = sum(1 << bit for bit in bits)
        s = syndrome(mask)
        assert table[s] is None
        table[s] = mask
assert None not in table
text = "/* SPDX-License-Identifier: GPL-3.0-or-later\n * Generated by generate_tables.py: perfect Golay(23,12,7), g(x)=0xc75. */\n"
text += "/* Per syndrome: data-bit correction mask << 2, plus error weight. */\n"
text += "static const uint16_t golay_errors[2048] = {\n"
for i in range(0, len(table), 8):
    text += "    " + ", ".join(f"0x{((v >> 11) << 2) | bin(v).count('1'):04x}u" for v in table[i:i+8]) + ",\n"
text += "};\n"
gf = []
v = 1
for _ in range(63):
    gf.append(v)
    v <<= 1
    if v & 64:
        v ^= 0x43
assert v == 1 and len(set(gf)) == 63
logs = [0] * 64
for i, v in enumerate(gf):
    logs[v] = i
for name, values in (("gf_exp", gf * 2), ("gf_log", logs)):
    text += f"static const uint8_t {name}[{len(values)}] = {{\n"
    for i in range(0, len(values), 16):
        text += "    " + ", ".join(str(v) for v in values[i:i+16]) + ",\n"
    text += "};\n"
destination = Path(__file__).with_name("golay_table.inc")
if "--check" in sys.argv:
    assert destination.read_text() == text, "generated Golay/GF tables differ"
else:
    destination.write_text(text)
