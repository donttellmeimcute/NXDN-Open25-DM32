"""Write or check a patch of the RadioFoundry derivative series.

The derivative tree (build/radiofoundry-p25) is generated by
tools/build_radiofoundry.py: transforms, copied sources, then the patches in
integration/radiofoundry/patches applied in name order. To change upstream
files, edit them in the derivative tree and run

    python3 tools/rf_patch.py make NNNN-name.patch path/in/tree.c ...

which diffs those files against the tree as the series before NNNN-name
leaves it and writes the patch. `check` verifies that the generated tree
matches the files on disk. No radio or network access.
"""
import argparse
import difflib
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools import build_radiofoundry as rf  # noqa: E402


def base_tree(limit):
    rf.STAGE.clear()
    rf.prepare(write=False, apply_series=True, limit=limit)
    return dict(rf.STAGE)


def make(name, paths):
    if not name.endswith(".patch"):
        raise SystemExit("patch names end in .patch")
    stage = base_tree(name)
    out = []
    for rel in paths:
        rel = str(Path(rel))
        if rel in stage:
            old = stage[rel][0]
        elif (rf.UP / rel).exists():
            old = (rf.UP / rel).read_bytes()
        else:
            old = None
        new_path = rf.DEST / rel
        new = new_path.read_bytes() if new_path.exists() else None
        if old == new:
            continue
        a = old.decode().splitlines(keepends=True) if old is not None else []
        b = new.decode().splitlines(keepends=True) if new is not None else []
        out.extend(difflib.unified_diff(a, b, "a/" + rel if old is not None else "/dev/null",
                                        "b/" + rel if new is not None else "/dev/null", n=3))
        if out and not out[-1].endswith("\n"):
            out[-1] += "\n\\ No newline at end of file\n"
    if not out:
        raise SystemExit("no changes in the listed files")
    rf.PATCHES.mkdir(parents=True, exist_ok=True)
    (rf.PATCHES / name).write_text("".join(out))
    print(f"wrote {rf.PATCHES / name}")


def check():
    stage = base_tree(None)
    bad = [k for k, (content, _) in stage.items() if (rf.DEST / k).read_bytes() != content]
    if bad:
        raise SystemExit("derivative tree differs from the series: " + ", ".join(bad))
    print("derivative tree matches the series")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("make")
    m.add_argument("name")
    m.add_argument("paths", nargs="+")
    sub.add_parser("check")
    args = ap.parse_args()
    if args.cmd == "make":
        make(args.name, args.paths)
    else:
        check()


if __name__ == "__main__":
    main()
