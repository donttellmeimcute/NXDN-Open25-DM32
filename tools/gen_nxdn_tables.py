"""Generate src/nxdn/nxdn_modem_tables.inc: the NXDN48 modem's filter tables at 8 kHz.

Transmit: a root-raised-cosine Nyquist filter, roll-off 0.2, times sin(x)/x with x = pi f / 2400 (the
symbol-length smoothing); receive: the root raised cosine times x/sin(x), which undoes it, so the two together
are a raised-cosine Nyquist channel. This is the structure MMDVM's NXDN modem uses (RRC 0.2 and its SINC
filter on transmit, RRC 0.2 and its ISINC filter on receive; research/protocol/MMDVM NXDNTX.cpp, IO.cpp).
Transmit is a 10-phase polyphase table (8000/2400 = 10/3: the sample-to-symbol phase repeats every 10
samples); receive is tabulated at 64 fractional sample phases for interpolated symbol timing. Q14 integers.

    python3 tools/gen_nxdn_tables.py
"""
import math
from pathlib import Path

FS, RS, BETA = 8000, 2400, 0.2
SPAN = 4                      # symbols each side
PHASES = 64                   # receive filter fractional phases per sample
OUT = Path(__file__).resolve().parents[1] / "src/nxdn/nxdn_modem_tables.inc"


def rrc(t):
    """Root raised cosine, symbol units, unit energy shape (peak 1 - b + 4b/pi)."""
    b = BETA
    if abs(t) < 1e-12:
        return 1 - b + 4 * b / math.pi
    if abs(abs(4 * b * t) - 1) < 1e-9:
        return b / math.sqrt(2) * ((1 + 2 / math.pi) * math.sin(math.pi / (4 * b)) + (1 - 2 / math.pi) * math.cos(math.pi / (4 * b)))
    return (math.sin(math.pi * t * (1 - b)) + 4 * b * t * math.cos(math.pi * t * (1 + b))) / (math.pi * t * (1 - (4 * b * t) ** 2))


def rrc_spectrum(f):
    """Frequency response of the RRC (f in units of the symbol rate)."""
    f, b = abs(f), BETA
    if f <= (1 - b) / 2:
        return 1.0
    if f >= (1 + b) / 2:
        return 0.0
    return math.sqrt(0.5 * (1 + math.cos(math.pi / b * (f - (1 - b) / 2))))


def shaped(t, inverse, bins=1024):
    """RRC times sin(x)/x (transmit) or x/sin(x) (receive), by numerical inverse transform (symbol units)."""
    top = (1 + BETA) / 2
    df = top / bins
    acc = 0.0
    for k in range(bins + 1):
        f = k * df
        x = math.pi * f
        p = 1.0 if not x else (x / math.sin(x) if inverse else math.sin(x) / x)
        w = 1 if k in (0, bins) else 2
        acc += w * rrc_spectrum(f) * p * math.cos(2 * math.pi * f * t)
    return acc * df


def tx_pulse(t):
    return shaped(t, False)


def q14(v):
    return int(round(v * 16384))


def main():
    sps = FS / RS
    # TX: output sample n sits 0.3 n symbols into the stream. For phase p = n mod 10, the symbol k = floor(0.3 n) - j
    # is (frac + j) symbols back, frac = 0.3 n - floor(0.3 n) = (3 p mod 10) / 10
    peak = tx_pulse(0)
    tx = []
    for p in range(10):
        frac = (3 * p % 10) / 10
        tx.append([q14(tx_pulse(frac + j) / peak) for j in range(-SPAN, SPAN + 1)])
    # RX: taps at sample offsets m - phase/PHASES for m = -half .. half
    half = int(math.ceil(SPAN * sps)) + 1
    cache = {}

    def rxp(t):
        k = round(t * 1e6)
        if k not in cache:
            cache[k] = shaped(t, True, 512)
        return cache[k]
    norm = sum(rxp(m / sps) for m in range(-half, half + 1))
    rx = []
    for ph in range(PHASES):
        rx.append([q14(rxp((m - ph / PHASES) / sps) / norm) for m in range(-half, half + 1)])
    lines = ["/* SPDX-License-Identifier: GPL-3.0-or-later */",
             "/* Generated by tools/gen_nxdn_tables.py: do not edit. */",
             f"#define NXDN_TX_TAPS {2 * SPAN + 1}",
             f"#define NXDN_RX_HALF {half}",
             f"#define NXDN_RX_TAPS {2 * half + 1}",
             f"#define NXDN_RX_PHASES {PHASES}",
             "static const int16_t nxdn_tx_pulse[10][NXDN_TX_TAPS] = {"]
    lines += ["    { " + ", ".join(map(str, row)) + " }," for row in tx]
    lines += ["};", "static const int16_t nxdn_rx_filter[NXDN_RX_PHASES][NXDN_RX_TAPS] = {"]
    lines += ["    { " + ", ".join(map(str, row)) + " }," for row in rx]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
