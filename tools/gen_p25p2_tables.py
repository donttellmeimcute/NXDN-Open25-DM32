"""Generate src/p25p2/p2_tables.inc from OP25's Phase 2 sources at the pinned commit (docs/protocol-sources.json):

- the I-ISCH code: OP25 apps/tdma/isch.py, the (40,9) generator matrix and the offset code word c0.

It also checks that the Phase 2 voice code word interleave (OP25 lib/p25p2_vf.cc interleave_vcw(), "vf[j] = cX[n];" with
n counted from the code word's least significant bit) is DMR's AMBE+2 air frame interleave (core/dmr/ambe/ambeFec.h:
air bit 4k = S(k), 4k+1 = S(18+k), 4k+2 = S(36+k), 4k+3 = S(54+k), S = C0 C1 C2 C3 most significant bit first), so
src/p25p2 passes voice code words to the DMR vocoder path unchanged; it stops if that ever stops being true.

    python3 tools/gen_p25p2_tables.py
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OP25 = ROOT / "research/protocol/op25/op25/gr-op25_repeater"
OUT = ROOT / "src/p25p2/p2_tables.inc"
LENS = {"c0": 24, "c1": 23, "c2": 11, "c3": 14}
START = {"c0": 0, "c1": 24, "c2": 47, "c3": 58}


def vcw_table():
    src = (OP25 / "lib/p25p2_vf.cc").read_text()
    body = src[src.index("void p25p2_vf::interleave_vcw"):]
    body = body[:body.index("for (size_t i=0")]
    seq = [None] * 72
    for j, cw, n in re.findall(r"vf\[(\d+)\] = (c[0-3])\[(\d+)\];", body):
        j, n = int(j), int(n)
        seq[j] = START[cw] + LENS[cw] - 1 - n
    assert None not in seq and sorted(seq) == list(range(72))
    return seq


def isch_code():
    src = (OP25 / "apps/tdma/isch.py").read_text()
    m = re.search(r"np\.asmatrix\('([01 ;]+)'\)", src)
    rows = [int("".join(r.split()), 2) for r in m.group(1).split(";")]
    c0 = int(re.search(r"c0 = (0x[0-9a-f]+)", src).group(1), 16)
    assert len(rows) == 9
    return rows, c0


def main():
    seq = vcw_table()
    assert seq == [18 * (j % 4) + j // 4 for j in range(72)], "Phase 2 voice interleave differs from DMR's"
    rows, c0 = isch_code()
    lines = ["/* Generated by tools/gen_p25p2_tables.py from OP25 (apps/tdma/isch.py). Do not edit. */"]
    lines.append("/* I-ISCH: code word = value (9 bits, most significant row first) x G, XOR c0 */")
    lines.append("static const uint64_t p2_isch_rows[9] = {")
    for r in rows:
        lines.append("    UINT64_C(0x%010x)," % r)
    lines.append("};")
    lines.append("#define P2_ISCH_C0 UINT64_C(0x%010x)" % c0)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
